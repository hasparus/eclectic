export const STRINGS: Record<Lang, Strings> = { pl, en };

export function detectLang(stored: string | null): Lang {
  if (stored === "pl" || stored === "en") return stored;
  const nav = typeof navigator !== "undefined" ? navigator.languages?.[0] || navigator.language || "" : "";
  return nav.toLowerCase().startsWith("en") ? "en" : "pl";
}

/** Polish uses a decimal comma. */
export const formatNumber = (lang: Lang, v: number, digits = 1): string =>
  v.toLocaleString(lang === "pl" ? "pl-PL" : "en-GB", { minimumFractionDigits: digits, maximumFractionDigits: digits });
