import { readdir, readFile, writeFile, access } from "node:fs/promises";
import { metadataSchema } from "../lib/prototype-schema";
const root = new URL("../", import.meta.url);
const exists = async (path: string) =>
  access(new URL(path, root)).then(
    () => true,
    () => false,
  );
const entries = [];
for (const dir of await readdir(new URL("app/prototypes/", root), {
  withFileTypes: true,
})) {
  if (!dir.isDirectory() || dir.name.startsWith("[")) continue;
  const slug = dir.name;
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug))
    throw new Error(`Invalid slug: ${slug}`);
  const meta = metadataSchema.parse(
    JSON.parse(
      await readFile(
        new URL(`app/prototypes/${slug}/metadata.json`, root),
        "utf8",
      ),
    ),
  );
  for (const file of ["page.tsx", "HOW_IT_WORKS.md"])
    if (!(await exists(`app/prototypes/${slug}/${file}`)))
      throw new Error(`${slug}: missing ${file}`);
  if (meta.public && !(await exists(`public/social/${slug}.mp4`)))
    throw new Error(
      `${slug}: public prototypes require social video; run thumbnails --video`,
    );
  entries.push({
    ...meta,
    slug,
    light: await exists(`public/thumbnails/${slug}-light.png`),
    dark: await exists(`public/thumbnails/${slug}-dark.png`),
  });
}
entries.sort((a, b) => b.updatedAt.localeCompare(a.updatedAt));
await writeFile(
  new URL("lib/registry.generated.ts", root),
  `// Generated by scripts/registry.ts. Do not edit.\nimport type { ComponentType } from "react";\n${entries.map((p, i) => `import P${i} from "@/app/prototypes/${p.slug}/page";`).join("\n")}\nexport const prototypes = ${JSON.stringify(entries, null, 2)};\nexport const pages: Record<string, ComponentType> = {${entries.map((p, i) => `${JSON.stringify(p.slug)}: P${i}`).join(",")}};\n`,
);
